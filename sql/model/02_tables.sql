-- Portable (Snowflake + DuckDB). Builds typed dimensional tables from STG_*.
-- In Snowflake, objects live in WHOLESALE_DEMO.DW.
CREATE OR REPLACE TABLE DIM_DATE AS
SELECT CAST(DATE_KEY AS DATE) AS DATE_KEY, CAST(WEEK_START AS DATE) AS WEEK_START,
       CAST(ISO_WEEK AS INTEGER) AS ISO_WEEK, YEAR_MONTH, YEAR_QUARTER,
       CAST(YEAR AS INTEGER) AS YEAR, DAY_NAME
FROM STG_DATE;

CREATE OR REPLACE TABLE DIM_CUSTOMER AS
SELECT CUSTOMER_ID, CUSTOMER_NAME, CHANNEL, REGION FROM STG_CUSTOMER;

CREATE OR REPLACE TABLE DIM_PRODUCT AS
SELECT SKU, STYLE_ID, STYLE_NAME, COLOR, SIZE, CATEGORY, SEASON,
       CAST(UNIT_COST AS DECIMAL(12,2)) AS UNIT_COST,
       CAST(WHOLESALE_PRICE AS DECIMAL(12,2)) AS WHOLESALE_PRICE
FROM STG_PRODUCT;

CREATE OR REPLACE TABLE FACT_ORDER_LINE AS
SELECT ORDER_ID, ORDER_LINE_ID, CAST(ORDER_DATE AS DATE) AS ORDER_DATE, CUSTOMER_ID, SKU,
       CAST(UNITS AS INTEGER) AS UNITS,
       CAST(UNIT_PRICE AS DECIMAL(12,2)) AS UNIT_PRICE,
       CAST(GROSS_SALES AS DECIMAL(14,2)) AS GROSS_SALES,
       CAST(DISCOUNT_AMOUNT AS DECIMAL(14,2)) AS DISCOUNT_AMOUNT,
       CAST(EXTENDED_COST AS DECIMAL(14,2)) AS EXTENDED_COST
FROM STG_ORDER_LINE;

CREATE OR REPLACE TABLE FACT_RETURN_LINE AS
SELECT RETURN_ID, ORDER_LINE_ID, CAST(RETURN_DATE AS DATE) AS RETURN_DATE,
       CAST(RETURNED_UNITS AS INTEGER) AS RETURNED_UNITS,
       CAST(REFUND_AMOUNT AS DECIMAL(14,2)) AS REFUND_AMOUNT,
       CAST(RETURNED_COST AS DECIMAL(14,2)) AS RETURNED_COST
FROM STG_RETURN_LINE;

CREATE OR REPLACE TABLE FACT_INVENTORY_SNAPSHOT AS
SELECT CAST(SNAPSHOT_DATE AS DATE) AS SNAPSHOT_DATE, SKU,
       CAST(UNITS_ON_HAND AS INTEGER) AS UNITS_ON_HAND,
       CAST(INVENTORY_COST AS DECIMAL(14,2)) AS INVENTORY_COST
FROM STG_INVENTORY_SNAPSHOT;
