-- Portable (Snowflake + DuckDB). Reporting views consumed by MicroStrategy.
-- RETURNS POLICY: returns are reported on RETURN_DATE (when the refund is issued),
-- attributed to the customer and SKU of the original order line.
-- GRAIN RULE: each fact is aggregated to date x customer x SKU on its own before combining.

CREATE OR REPLACE VIEW VW_WHOLESALE_SALES AS
WITH sales AS (
    SELECT ORDER_DATE AS ACTIVITY_DATE, CUSTOMER_ID, SKU,
           SUM(UNITS) AS UNITS_SOLD, SUM(GROSS_SALES) AS GROSS_SALES,
           SUM(DISCOUNT_AMOUNT) AS DISCOUNT_AMOUNT, SUM(EXTENDED_COST) AS SOLD_COST,
           COUNT(*) AS ORDER_LINE_COUNT
    FROM FACT_ORDER_LINE
    GROUP BY 1, 2, 3
), rets AS (
    SELECT r.RETURN_DATE AS ACTIVITY_DATE, o.CUSTOMER_ID, o.SKU,
           SUM(r.RETURNED_UNITS) AS UNITS_RETURNED, SUM(r.REFUND_AMOUNT) AS REFUND_AMOUNT,
           SUM(r.RETURNED_COST) AS RETURNED_COST
    FROM FACT_RETURN_LINE r
    JOIN FACT_ORDER_LINE o ON o.ORDER_LINE_ID = r.ORDER_LINE_ID
    GROUP BY 1, 2, 3
), keys AS (
    SELECT ACTIVITY_DATE, CUSTOMER_ID, SKU FROM sales
    UNION
    SELECT ACTIVITY_DATE, CUSTOMER_ID, SKU FROM rets
)
SELECT k.ACTIVITY_DATE, d.WEEK_START, d.YEAR_MONTH, d.YEAR,
       k.CUSTOMER_ID, c.CUSTOMER_NAME, c.CHANNEL, c.REGION,
       k.SKU, p.STYLE_ID, p.STYLE_NAME, p.COLOR, p.SIZE, p.CATEGORY, p.SEASON,
       COALESCE(s.UNITS_SOLD, 0)        AS UNITS_SOLD,
       COALESCE(r.UNITS_RETURNED, 0)    AS UNITS_RETURNED,
       COALESCE(s.GROSS_SALES, 0)       AS GROSS_SALES,
       COALESCE(s.DISCOUNT_AMOUNT, 0)   AS DISCOUNT_AMOUNT,
       COALESCE(r.REFUND_AMOUNT, 0)     AS REFUND_AMOUNT,
       COALESCE(s.SOLD_COST, 0)         AS SOLD_COST,
       COALESCE(r.RETURNED_COST, 0)     AS RETURNED_COST,
       COALESCE(s.ORDER_LINE_COUNT, 0)  AS ORDER_LINE_COUNT,
       COALESCE(s.GROSS_SALES, 0) - COALESCE(s.DISCOUNT_AMOUNT, 0) - COALESCE(r.REFUND_AMOUNT, 0) AS NET_SALES,
       COALESCE(s.UNITS_SOLD, 0) - COALESCE(r.UNITS_RETURNED, 0) AS NET_UNITS,
       COALESCE(s.SOLD_COST, 0) - COALESCE(r.RETURNED_COST, 0)   AS NET_COST
FROM keys k
LEFT JOIN sales s ON s.ACTIVITY_DATE = k.ACTIVITY_DATE AND s.CUSTOMER_ID = k.CUSTOMER_ID AND s.SKU = k.SKU
LEFT JOIN rets  r ON r.ACTIVITY_DATE = k.ACTIVITY_DATE AND r.CUSTOMER_ID = k.CUSTOMER_ID AND r.SKU = k.SKU
JOIN DIM_DATE d     ON d.DATE_KEY = k.ACTIVITY_DATE
JOIN DIM_CUSTOMER c ON c.CUSTOMER_ID = k.CUSTOMER_ID
JOIN DIM_PRODUCT p  ON p.SKU = k.SKU;

CREATE OR REPLACE VIEW VW_INVENTORY_POSITION AS
SELECT i.SNAPSHOT_DATE, i.SKU, p.STYLE_ID, p.STYLE_NAME, p.COLOR, p.SIZE, p.CATEGORY, p.SEASON,
       i.UNITS_ON_HAND, i.INVENTORY_COST,
       CASE WHEN i.SNAPSHOT_DATE = MAX(i.SNAPSHOT_DATE) OVER () THEN TRUE ELSE FALSE END AS IS_LATEST_SNAPSHOT
FROM FACT_INVENTORY_SNAPSHOT i
JOIN DIM_PRODUCT p ON p.SKU = i.SKU;

-- Weekly summary with prior-week comparison. Inventory is a stock measure, so it is taken
-- from the week's closing snapshot only, never summed across snapshots.
CREATE OR REPLACE VIEW VW_WEEKLY_WHOLESALE_SUMMARY AS
WITH wk AS (
    SELECT WEEK_START, CATEGORY,
           SUM(GROSS_SALES) AS GROSS_SALES, SUM(DISCOUNT_AMOUNT) AS DISCOUNT_AMOUNT,
           SUM(REFUND_AMOUNT) AS REFUND_AMOUNT, SUM(NET_SALES) AS NET_SALES,
           SUM(NET_UNITS) AS NET_UNITS, SUM(NET_COST) AS NET_COST,
           SUM(NET_SALES) - SUM(NET_COST) AS GROSS_MARGIN
    FROM VW_WHOLESALE_SALES
    GROUP BY 1, 2
), inv AS (
    SELECT i.SNAPSHOT_DATE, p.CATEGORY, SUM(i.UNITS_ON_HAND) AS CLOSING_UNITS_ON_HAND
    FROM FACT_INVENTORY_SNAPSHOT i JOIN DIM_PRODUCT p ON p.SKU = i.SKU
    GROUP BY 1, 2
)
SELECT wk.*,
       CASE WHEN wk.NET_SALES = 0 THEN NULL ELSE wk.GROSS_MARGIN / wk.NET_SALES END AS GROSS_MARGIN_PCT,
       LAG(wk.NET_SALES)    OVER (PARTITION BY wk.CATEGORY ORDER BY wk.WEEK_START) AS PRIOR_WEEK_NET_SALES,
       LAG(wk.GROSS_MARGIN) OVER (PARTITION BY wk.CATEGORY ORDER BY wk.WEEK_START) AS PRIOR_WEEK_GROSS_MARGIN,
       inv.CLOSING_UNITS_ON_HAND
FROM wk
LEFT JOIN inv ON inv.CATEGORY = wk.CATEGORY
             AND inv.SNAPSHOT_DATE = wk.WEEK_START + 6;
