-- Investigation steps. Run in order; each narrows the difference.
-- Step 1: dashboard (view) total vs independent fact total
SELECT 'STEP1_TOTAL' AS STEP, v.X AS DASHBOARD_NET_SALES, f.X AS INDEPENDENT_NET_SALES, v.X - f.X AS DIFF
FROM (SELECT SUM(NET_SALES) AS X FROM VW_WHOLESALE_SALES) v,
     (SELECT (SELECT SUM(GROSS_SALES - DISCOUNT_AMOUNT) FROM FACT_ORDER_LINE)
           - (SELECT SUM(REFUND_AMOUNT) FROM FACT_RETURN_LINE) AS X) f;

-- Step 2: which weeks differ (sales side only, top 5)
SELECT 'STEP2_BY_WEEK' AS STEP, v.WEEK_START, v.X AS VIEW_SALES, f.X AS FACT_SALES, v.X - f.X AS DIFF
FROM (SELECT WEEK_START, SUM(GROSS_SALES - DISCOUNT_AMOUNT) AS X FROM VW_WHOLESALE_SALES GROUP BY 1) v
JOIN (SELECT d.WEEK_START, SUM(o.GROSS_SALES - o.DISCOUNT_AMOUNT) AS X
      FROM FACT_ORDER_LINE o JOIN DIM_DATE d ON d.DATE_KEY = o.ORDER_DATE GROUP BY 1) f USING (WEEK_START)
WHERE ABS(v.X - f.X) > 0.01 ORDER BY ABS(v.X - f.X) DESC LIMIT 5;

-- Step 3: which customers differ
SELECT 'STEP3_BY_CUSTOMER' AS STEP, v.CUSTOMER_ID, v.X - f.X AS DIFF
FROM (SELECT CUSTOMER_ID, SUM(GROSS_SALES - DISCOUNT_AMOUNT) AS X FROM VW_WHOLESALE_SALES GROUP BY 1) v
JOIN (SELECT CUSTOMER_ID, SUM(GROSS_SALES - DISCOUNT_AMOUNT) AS X FROM FACT_ORDER_LINE GROUP BY 1) f USING (CUSTOMER_ID)
WHERE ABS(v.X - f.X) > 0.01 ORDER BY 3 DESC, 2;

-- Step 4: which SKUs differ - differences spread across customers but concentrate in SKUs
SELECT 'STEP4_BY_SKU' AS STEP, v.SKU, v.N AS VIEW_LINE_COUNT, f.N AS FACT_LINE_COUNT, v.X - f.X AS DIFF
FROM (SELECT SKU, SUM(ORDER_LINE_COUNT) AS N, SUM(GROSS_SALES - DISCOUNT_AMOUNT) AS X FROM VW_WHOLESALE_SALES GROUP BY 1) v
JOIN (SELECT SKU, COUNT(*) AS N, SUM(GROSS_SALES - DISCOUNT_AMOUNT) AS X FROM FACT_ORDER_LINE GROUP BY 1) f USING (SKU)
WHERE v.N <> f.N ORDER BY 5 DESC;

-- Step 5: check keys on every table the view joins
SELECT 'STEP5_DUP_KEYS' AS STEP, 'DIM_PRODUCT' AS TBL, SKU AS KEY_VALUE, COUNT(*) AS ROWS_PER_KEY
FROM DIM_PRODUCT GROUP BY SKU HAVING COUNT(*) > 1
UNION ALL
SELECT 'STEP5_DUP_KEYS', 'DIM_CUSTOMER', CUSTOMER_ID, COUNT(*) FROM DIM_CUSTOMER GROUP BY CUSTOMER_ID HAVING COUNT(*) > 1
UNION ALL
SELECT 'STEP5_DUP_KEYS', 'DIM_DATE', CAST(DATE_KEY AS VARCHAR), COUNT(*) FROM DIM_DATE GROUP BY DATE_KEY HAVING COUNT(*) > 1;

-- Step 6: show the duplicate rows
SELECT 'STEP6_DUP_ROWS' AS STEP, SKU, STYLE_NAME, SEASON FROM DIM_PRODUCT WHERE SKU = 'ST120-BLK-M';
