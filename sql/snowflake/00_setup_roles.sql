-- Snowflake-only. Run as SECURITYADMIN / SYSADMIN in a demo account.
-- Least-privilege demo roles: a loader that writes, a reporting role that only reads views.
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS WHS_DEMO_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE DATABASE IF NOT EXISTS WHOLESALE_DEMO;
-- One schema keeps the demo simple: STG_* (raw), DIM_/FACT_ (typed), VW_* (reporting).
CREATE SCHEMA IF NOT EXISTS WHOLESALE_DEMO.DW;

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS WHS_LOADER;      -- loads STG, builds DW and RPT
CREATE ROLE IF NOT EXISTS WHS_REPORTING;   -- MicroStrategy service account: read RPT views only
GRANT ROLE WHS_LOADER TO ROLE SYSADMIN;
GRANT ROLE WHS_REPORTING TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE WHS_DEMO_WH TO ROLE WHS_LOADER;
GRANT USAGE ON WAREHOUSE WHS_DEMO_WH TO ROLE WHS_REPORTING;
GRANT USAGE ON DATABASE WHOLESALE_DEMO TO ROLE WHS_LOADER;
GRANT USAGE ON DATABASE WHOLESALE_DEMO TO ROLE WHS_REPORTING;
GRANT ALL ON SCHEMA WHOLESALE_DEMO.DW TO ROLE WHS_LOADER;

-- Reporting role: SELECT on views only. No table grants, so MicroStrategy cannot bypass
-- the reporting layer. Views execute with the owner's (WHS_LOADER) privileges.
GRANT USAGE ON SCHEMA WHOLESALE_DEMO.DW TO ROLE WHS_REPORTING;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA WHOLESALE_DEMO.DW TO ROLE WHS_REPORTING;

