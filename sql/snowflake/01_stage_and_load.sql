-- Snowflake-only. Creates STG tables and loads CSVs from an internal stage.
-- tests/run.py --target snowflake runs the PUT for you. Manual equivalent:
--   PUT file://data/*.csv @WHOLESALE_DEMO.DW.WHS_STAGE AUTO_COMPRESS=TRUE;
USE ROLE WHS_LOADER;
USE WAREHOUSE WHS_DEMO_WH;
USE SCHEMA WHOLESALE_DEMO.DW;

CREATE OR REPLACE FILE FORMAT CSV_FMT TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"';
CREATE STAGE IF NOT EXISTS WHS_STAGE FILE_FORMAT = CSV_FMT;

CREATE OR REPLACE TABLE STG_DATE (DATE_KEY VARCHAR, WEEK_START VARCHAR, ISO_WEEK VARCHAR, YEAR_MONTH VARCHAR, YEAR_QUARTER VARCHAR, YEAR VARCHAR, DAY_NAME VARCHAR);
CREATE OR REPLACE TABLE STG_CUSTOMER (CUSTOMER_ID VARCHAR, CUSTOMER_NAME VARCHAR, CHANNEL VARCHAR, REGION VARCHAR);
CREATE OR REPLACE TABLE STG_PRODUCT (SKU VARCHAR, STYLE_ID VARCHAR, STYLE_NAME VARCHAR, COLOR VARCHAR, SIZE VARCHAR, CATEGORY VARCHAR, SEASON VARCHAR, UNIT_COST VARCHAR, WHOLESALE_PRICE VARCHAR);
CREATE OR REPLACE TABLE STG_ORDER_LINE (ORDER_ID VARCHAR, ORDER_LINE_ID VARCHAR, ORDER_DATE VARCHAR, CUSTOMER_ID VARCHAR, SKU VARCHAR, UNITS VARCHAR, UNIT_PRICE VARCHAR, GROSS_SALES VARCHAR, DISCOUNT_AMOUNT VARCHAR, EXTENDED_COST VARCHAR);
CREATE OR REPLACE TABLE STG_RETURN_LINE (RETURN_ID VARCHAR, ORDER_LINE_ID VARCHAR, RETURN_DATE VARCHAR, RETURNED_UNITS VARCHAR, REFUND_AMOUNT VARCHAR, RETURNED_COST VARCHAR);
CREATE OR REPLACE TABLE STG_INVENTORY_SNAPSHOT (SNAPSHOT_DATE VARCHAR, SKU VARCHAR, UNITS_ON_HAND VARCHAR, INVENTORY_COST VARCHAR);

COPY INTO STG_DATE               FROM @WHS_STAGE/dim_date.csv.gz;
COPY INTO STG_CUSTOMER           FROM @WHS_STAGE/dim_customer.csv.gz;
COPY INTO STG_PRODUCT            FROM @WHS_STAGE/dim_product.csv.gz;
COPY INTO STG_ORDER_LINE         FROM @WHS_STAGE/fact_order_line.csv.gz;
COPY INTO STG_RETURN_LINE        FROM @WHS_STAGE/fact_return_line.csv.gz;
COPY INTO STG_INVENTORY_SNAPSHOT FROM @WHS_STAGE/fact_inventory_snapshot.csv.gz;
