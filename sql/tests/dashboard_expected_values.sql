-- Expected values for validating the MicroStrategy dashboard. Compute independently from
-- the FACT tables (not the reporting views) and compare to the dashboard for the same prompts.
-- Default prompt answers: full period, all customers. Edit the dates/customer to test other prompts.

-- KPI cards (returns on return date)
SELECT
  (SELECT SUM(GROSS_SALES - DISCOUNT_AMOUNT) FROM FACT_ORDER_LINE) - (SELECT SUM(REFUND_AMOUNT) FROM FACT_RETURN_LINE) AS NET_SALES,
  (SELECT SUM(UNITS) FROM FACT_ORDER_LINE) - (SELECT SUM(RETURNED_UNITS) FROM FACT_RETURN_LINE) AS NET_UNITS,
  ((SELECT SUM(GROSS_SALES - DISCOUNT_AMOUNT - EXTENDED_COST) FROM FACT_ORDER_LINE)
    - (SELECT SUM(REFUND_AMOUNT - RETURNED_COST) FROM FACT_RETURN_LINE)) AS GROSS_MARGIN;

-- Net sales by customer
SELECT CUSTOMER_ID, SUM(AMT) AS NET_SALES FROM (
  SELECT CUSTOMER_ID, GROSS_SALES - DISCOUNT_AMOUNT AS AMT FROM FACT_ORDER_LINE
  UNION ALL
  SELECT o.CUSTOMER_ID, -r.REFUND_AMOUNT FROM FACT_RETURN_LINE r JOIN FACT_ORDER_LINE o ON o.ORDER_LINE_ID = r.ORDER_LINE_ID
) x GROUP BY CUSTOMER_ID ORDER BY CUSTOMER_ID;

-- Latest inventory on hand (single snapshot)
SELECT SNAPSHOT_DATE, SUM(UNITS_ON_HAND) AS UNITS_ON_HAND FROM FACT_INVENTORY_SNAPSHOT
WHERE SNAPSHOT_DATE = (SELECT MAX(SNAPSHOT_DATE) FROM FACT_INVENTORY_SNAPSHOT) GROUP BY 1;
