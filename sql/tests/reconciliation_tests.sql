-- Portable test suite. Each statement returns TEST_NAME, STATUS, DETAIL.
-- Tolerance for money comparisons: 0.01 (one cent) on totals.

-- T01 primary keys
SELECT 'T01_PK_FACT_ORDER_LINE' AS TEST_NAME,
       CASE WHEN COUNT(*) = COUNT(DISTINCT ORDER_LINE_ID) THEN 'PASS' ELSE 'FAIL' END AS STATUS,
       CAST(COUNT(*) - COUNT(DISTINCT ORDER_LINE_ID) AS VARCHAR) || ' duplicate keys' AS DETAIL
FROM FACT_ORDER_LINE;

SELECT 'T02_PK_DIM_PRODUCT', CASE WHEN COUNT(*) = COUNT(DISTINCT SKU) THEN 'PASS' ELSE 'FAIL' END,
       CAST(COUNT(*) - COUNT(DISTINCT SKU) AS VARCHAR) || ' duplicate SKUs'
FROM DIM_PRODUCT;

SELECT 'T03_PK_DIM_CUSTOMER', CASE WHEN COUNT(*) = COUNT(DISTINCT CUSTOMER_ID) THEN 'PASS' ELSE 'FAIL' END,
       CAST(COUNT(*) - COUNT(DISTINCT CUSTOMER_ID) AS VARCHAR) || ' duplicate customers'
FROM DIM_CUSTOMER;

SELECT 'T04_PK_INVENTORY_SNAPSHOT', CASE WHEN COUNT(*) = COUNT(DISTINCT SNAPSHOT_DATE || '|' || SKU) THEN 'PASS' ELSE 'FAIL' END,
       CAST(COUNT(*) - COUNT(DISTINCT SNAPSHOT_DATE || '|' || SKU) AS VARCHAR) || ' duplicate date/SKU rows'
FROM FACT_INVENTORY_SNAPSHOT;

-- T05 required fields
SELECT 'T05_REQUIRED_FIELDS_ORDER_LINE',
       CASE WHEN SUM(CASE WHEN ORDER_DATE IS NULL OR CUSTOMER_ID IS NULL OR SKU IS NULL OR UNITS IS NULL OR GROSS_SALES IS NULL THEN 1 ELSE 0 END) = 0 THEN 'PASS' ELSE 'FAIL' END,
       CAST(SUM(CASE WHEN ORDER_DATE IS NULL OR CUSTOMER_ID IS NULL OR SKU IS NULL OR UNITS IS NULL OR GROSS_SALES IS NULL THEN 1 ELSE 0 END) AS VARCHAR) || ' rows with nulls'
FROM FACT_ORDER_LINE;

-- T06 referential integrity: every fact row finds its dimension rows
SELECT 'T06_ORPHAN_ORDER_LINES',
       CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL' END, CAST(COUNT(*) AS VARCHAR) || ' orphan rows'
FROM FACT_ORDER_LINE o
LEFT JOIN DIM_PRODUCT p ON p.SKU = o.SKU
LEFT JOIN DIM_CUSTOMER c ON c.CUSTOMER_ID = o.CUSTOMER_ID
WHERE p.SKU IS NULL OR c.CUSTOMER_ID IS NULL;

SELECT 'T07_ORPHAN_RETURN_LINES',
       CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL' END, CAST(COUNT(*) AS VARCHAR) || ' returns without an order line'
FROM FACT_RETURN_LINE r LEFT JOIN FACT_ORDER_LINE o ON o.ORDER_LINE_ID = r.ORDER_LINE_ID
WHERE o.ORDER_LINE_ID IS NULL;

-- T08 join fan-out: order lines counted through the view = order lines in the fact
SELECT 'T08_VIEW_DOES_NOT_MULTIPLY_ORDER_LINES',
       CASE WHEN v.N = f.N THEN 'PASS' ELSE 'FAIL' END,
       'view=' || CAST(v.N AS VARCHAR) || ' fact=' || CAST(f.N AS VARCHAR)
FROM (SELECT SUM(ORDER_LINE_COUNT) AS N FROM VW_WHOLESALE_SALES) v,
     (SELECT COUNT(*) AS N FROM FACT_ORDER_LINE) f;

-- T09 reconciliation: view net sales vs independent calculation from facts only (no dimension joins)
SELECT 'T09_RECON_NET_SALES_TOTAL',
       CASE WHEN ABS(v.X - (f.G - f.D - r.R)) <= 0.01 THEN 'PASS' ELSE 'FAIL' END,
       'view=' || CAST(v.X AS VARCHAR) || ' independent=' || CAST(f.G - f.D - r.R AS VARCHAR)
FROM (SELECT SUM(NET_SALES) AS X FROM VW_WHOLESALE_SALES) v,
     (SELECT SUM(GROSS_SALES) AS G, SUM(DISCOUNT_AMOUNT) AS D FROM FACT_ORDER_LINE) f,
     (SELECT SUM(REFUND_AMOUNT) AS R FROM FACT_RETURN_LINE) r;

SELECT 'T10_RECON_GROSS_MARGIN_TOTAL',
       CASE WHEN ABS(v.X - ((f.G - f.D - r.R) - (f.C - r.C))) <= 0.01 THEN 'PASS' ELSE 'FAIL' END,
       'view=' || CAST(v.X AS VARCHAR) || ' independent=' || CAST((f.G - f.D - r.R) - (f.C - r.C) AS VARCHAR)
FROM (SELECT SUM(NET_SALES) - SUM(NET_COST) AS X FROM VW_WHOLESALE_SALES) v,
     (SELECT SUM(GROSS_SALES) AS G, SUM(DISCOUNT_AMOUNT) AS D, SUM(EXTENDED_COST) AS C FROM FACT_ORDER_LINE) f,
     (SELECT SUM(REFUND_AMOUNT) AS R, SUM(RETURNED_COST) AS C FROM FACT_RETURN_LINE) r;

-- T11 filtered reconciliation (simulates a dashboard prompt: one customer, one month)
SELECT 'T11_RECON_FILTERED_C002_2026_03',
       CASE WHEN ABS(v.X - (f.X - COALESCE(r.X, 0))) <= 0.01 THEN 'PASS' ELSE 'FAIL' END,
       'view=' || CAST(v.X AS VARCHAR) || ' independent=' || CAST(f.X - COALESCE(r.X, 0) AS VARCHAR)
FROM (SELECT SUM(NET_SALES) AS X FROM VW_WHOLESALE_SALES
      WHERE CUSTOMER_ID = 'C002' AND ACTIVITY_DATE BETWEEN DATE '2026-03-01' AND DATE '2026-03-31') v,
     (SELECT SUM(GROSS_SALES - DISCOUNT_AMOUNT) AS X FROM FACT_ORDER_LINE
      WHERE CUSTOMER_ID = 'C002' AND ORDER_DATE BETWEEN DATE '2026-03-01' AND DATE '2026-03-31') f,
     (SELECT SUM(r.REFUND_AMOUNT) AS X FROM FACT_RETURN_LINE r JOIN FACT_ORDER_LINE o ON o.ORDER_LINE_ID = r.ORDER_LINE_ID
      WHERE o.CUSTOMER_ID = 'C002' AND r.RETURN_DATE BETWEEN DATE '2026-03-01' AND DATE '2026-03-31') r;

-- T12 weekly summary sums back to the detail view
SELECT 'T12_WEEKLY_SUMMARY_TIES_TO_DETAIL',
       CASE WHEN ABS(w.X - v.X) <= 0.01 THEN 'PASS' ELSE 'FAIL' END,
       'weekly=' || CAST(w.X AS VARCHAR) || ' detail=' || CAST(v.X AS VARCHAR)
FROM (SELECT SUM(NET_SALES) AS X FROM VW_WEEKLY_WHOLESALE_SUMMARY) w,
     (SELECT SUM(NET_SALES) AS X FROM VW_WHOLESALE_SALES) v;

-- T13 inventory uses one snapshot, not a sum across dates
SELECT 'T13_INVENTORY_LATEST_SNAPSHOT_ONLY',
       CASE WHEN v.X = f.X AND v.D = 1 THEN 'PASS' ELSE 'FAIL' END,
       'latest flag units=' || CAST(v.X AS VARCHAR) || ' max-date units=' || CAST(f.X AS VARCHAR) || ' distinct dates flagged=' || CAST(v.D AS VARCHAR)
FROM (SELECT SUM(UNITS_ON_HAND) AS X, COUNT(DISTINCT SNAPSHOT_DATE) AS D FROM VW_INVENTORY_POSITION WHERE IS_LATEST_SNAPSHOT) v,
     (SELECT SUM(UNITS_ON_HAND) AS X FROM FACT_INVENTORY_SNAPSHOT
      WHERE SNAPSHOT_DATE = (SELECT MAX(SNAPSHOT_DATE) FROM FACT_INVENTORY_SNAPSHOT)) f;

-- T14 return quantity never exceeds sold quantity for its line
SELECT 'T14_RETURNS_NOT_EXCEED_SOLD',
       CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL' END, CAST(COUNT(*) AS VARCHAR) || ' over-returned lines'
FROM (SELECT r.ORDER_LINE_ID, SUM(r.RETURNED_UNITS) AS RU, MAX(o.UNITS) AS U
      FROM FACT_RETURN_LINE r JOIN FACT_ORDER_LINE o ON o.ORDER_LINE_ID = r.ORDER_LINE_ID
      GROUP BY r.ORDER_LINE_ID) x
WHERE RU > U;
